#!/usr/bin/env bash
# portage-tune.sh — apply parallel build settings for high-core builders
#
# Env / build-args (0 = auto from nproc):
#   BUILD_JOBS   make -j per package (default: nproc - 4, min 2)
#   EMERGE_JOBS  emerge --jobs parallel packages (default: nproc/8, min 1, max 8)
#   BUILD_LOAD   make -l / load-average cap (default: nproc + nproc/4)
#
# Example 32-core / 128GB server:
#   BUILD_JOBS=28 EMERGE_JOBS=4 BUILD_LOAD=36

set -euo pipefail

NCPUS="$(nproc)"

BUILD_JOBS="${BUILD_JOBS:-0}"
EMERGE_JOBS="${EMERGE_JOBS:-0}"
BUILD_LOAD="${BUILD_LOAD:-0}"

if [ "${BUILD_JOBS}" -gt 0 ] 2>/dev/null; then
    MAKE_JOBS="${BUILD_JOBS}"
else
    MAKE_JOBS=$(( NCPUS > 6 ? NCPUS - 4 : NCPUS ))
fi

if [ "${EMERGE_JOBS}" -gt 0 ] 2>/dev/null; then
    EMERGE_PARALLEL="${EMERGE_JOBS}"
else
    EMERGE_PARALLEL=$(( NCPUS / 8 ))
    [ "${EMERGE_PARALLEL}" -lt 1 ] && EMERGE_PARALLEL=1
    [ "${EMERGE_PARALLEL}" -gt 8 ] && EMERGE_PARALLEL=8
fi

if [ "${BUILD_LOAD:-0}" -gt 0 ] 2>/dev/null; then
    LOAD="${BUILD_LOAD}"
else
    LOAD=$(( NCPUS + NCPUS / 4 ))
fi

CONF="/etc/portage/make.conf.d/performance.conf"
mkdir -p /etc/portage/make.conf.d

cat > "${CONF}" <<EOF
# Generated by portage-tune.sh — ${NCPUS} CPUs detected
MAKEOPTS="-j${MAKE_JOBS} -l${LOAD}"
EMERGE_DEFAULT_OPTS="\${EMERGE_DEFAULT_OPTS} --jobs=${EMERGE_PARALLEL} --load-average=${LOAD}"
EOF

# ccache when available (installed in @php-toolchain)
if command -v ccache >/dev/null 2>&1; then
    cat >> "${CONF}" <<'EOF'
FEATURES="${FEATURES} ccache"
EOF
    mkdir -p /var/cache/ccache
    cat >> /etc/portage/make.conf.d/ccache.conf <<EOF
CCACHE_DIR="/var/cache/ccache"
CCACHE_MAXSIZE="20G"
CCACHE_COMPRESS=1
CCACHE_COMPRESSLEVEL=6
EOF
fi

echo ">>> portage-tune: CPUs=${NCPUS} MAKEOPTS=-j${MAKE_JOBS} emerge --jobs=${EMERGE_PARALLEL} load=${LOAD}"
